'''演示特征预处理之一归一化操作
特征工程：目的：利用专业的背景知识，和技巧处理数据，用于提升模型的性能。
步骤：1.特征提取
2.特征预处理（归一化，标准化)
3.特征降维
4.特征选择
5.特征组合

归一化目的：防止因为量纲问题导致特征里的方差相差较大，影响模型的最终效果。
  通过公式把各列的值映射到[0,1]区间
公式：x'=（当前值-该列最小值）/（该列最大值-该列最小值）
  x''=x'*(mx-mi)+mi
  公式解析：x' :基于公式算出来的结果
     x'' ：最终的结果
     mx 区间的最大值
     mi 区间的最小值
弊端：
  容易受到极值影响，一般用于处理小数据集
'''

#导包
from sklearn.preprocessing import MinMaxScaler #归一化对象

#1.准备数据集
x_train=[[90,2,10,40],[60,4,15,45],[75,3,13,46]]

#2.创建归一化对象
#参数feature_range表示生成范围，默认（0，1）可以不写
transfer=MinMaxScaler(feature_range=(0,1))

#3.对数据进行归一化操作
x_train_new=transfer.fit_transform(x_train)

#4.打印处理后的数据
print('归一化的数据集为：\n')
print(x_train_new)